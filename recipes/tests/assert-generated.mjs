import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const text = name => readFileSync(new URL(name, import.meta.url), 'utf8')
const json = name => JSON.parse(text(name))

const app = json('appManifest')
assert.equal(app.name, '@internal/app')
assert.equal(app.dependencies['@internal/lib'], 'file:./lib.tgz')
assert.equal(app.private, true)
assert.equal(app.scripts.test, 'vitest run')
assert.equal(app.scripts.lint, 'eslint .')
assert.equal(json('packManifest').dependencies['@internal/lib'], '>=0.0.0')
assert.equal(json('packManifest').main, './dist/index.js')
const tsconfig = json('appTsconfig')
assert.equal(tsconfig.compilerOptions.declaration, true)
assert.equal(tsconfig.compilerOptions.moduleResolution, 'NodeNext')
assert.match(text('appTest'), /environment: "node"/)
assert.match(text('appLint'), /eslint-plugin-prettier/)
assert.equal(json('appPrettier').singleQuote, true)
assert.match(text('appPnpm'), /esbuild/)
assert.match(text('appRollup'), /dist\/app\.js/)
assert.deepEqual(json('appDocs').entryPoints, ['src/index.ts'])
assert.equal(json('workerManifest').main, undefined)
assert.equal(json('workerTsconfig').compilerOptions.noEmit, true)
assert.match(text('workerYarn'), /nodeLinker: node-modules/)
assert.ok(json('webManifest').dependencies.react)
assert.match(text('webVite'), /tailwindcss/)
assert.match(text('webTest'), /mergeConfig/)
console.log('generated file assertions passed')
